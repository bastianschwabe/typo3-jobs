def parse(grid: str) -> list[list[bool]]:
    rows = [line for line in grid.strip("\n").splitlines()]
    assert len(rows) == 16, f"expected 16 rows, got {len(rows)}"
    for row in rows:
        assert len(row) == 16, f"expected 16 columns in {row!r}"
    return [[c == "#" for c in row] for row in rows]


def rectangles(cells: list[list[bool]]) -> list[tuple[int, int, int, int]]:
    """Greedy merge of horizontal runs into rectangles (x, y, w, h)."""
    used = [[False] * 16 for _ in range(16)]
    rects = []
    for y in range(16):
        x = 0
        while x < 16:
            if not cells[y][x] or used[y][x]:
                x += 1
                continue
            w = 0
            while x + w < 16 and cells[y][x + w] and not used[y][x + w]:
                w += 1
            h = 1
            while y + h < 16 and all(
                cells[y + h][x + i] and not used[y + h][x + i] for i in range(w)
            ):
                h += 1
            for dy in range(h):
                for dx in range(w):
                    used[y + dy][x + dx] = True
            rects.append((x, y, w, h))
            x += w
    return rects


def path_data(cells: list[list[bool]]) -> str:
    return "".join(f"M{x} {y}h{w}v{h}h-{w}z" for x, y, w, h in rectangles(cells))


HEAD = (
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {vb} {vb}" '
    'width="{size}" height="{size}" shape-rendering="crispEdges" aria-hidden="true">'
)
NOTE = "<!-- NEUEDATEN CD 2026, pixel icon: 16-unit grid, 2 px forms, no curves. Source: Build/Icons/generate.py -->"


def write_icon(name: str, grid: str) -> None:
    d = path_data(parse(grid))
    if name in TILES:
        bg, fg = TILES[name]
        body = f'<rect width="16" height="16" fill="{bg}"/><path fill="{fg}" d="{d}"/>'
    else:
        body = f'<path fill="currentColor" d="{d}"/>'
    svg = HEAD.format(vb=16, size=16) + NOTE + body + "</svg>\n"
    (OUT / f"{name}.svg").write_text(svg)


def write_extension_icon() -> None:
    """Extension and favicon tile: the briefcase in lime on a violet ground,
    the pairing the CD sets for the app icon. 24-unit field, glyph offset 4."""
    d = path_data(parse(GRIDS["tx_jobs_domain_model_job"]))
    svg = (
        HEAD.format(vb=24, size=96)
        + NOTE
        + f'<rect width="24" height="24" fill="{VIOLET}"/>'
        + f'<path fill="{LIME}" transform="translate(4 4)" d="{d}"/></svg>\n'
    )
    (OUT / "Extension.svg").write_text(svg)


if __name__ == "__main__":
    for name, grid in GRIDS.items():
        write_icon(name, grid)
    write_extension_icon()
    print(f"wrote {len(GRIDS) + 1} icons to {OUT}")
